CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) UNIQUE NOT NULL,
 display_name VARCHAR(120) NOT NULL,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(16) NOT NULL DEFAULT 'STUDENT' CHECK(role IN ('STUDENT','TEACHER','ADMIN')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE accounts DROP CONSTRAINT IF EXISTS accounts_role_check;
ALTER TABLE accounts ADD CONSTRAINT accounts_role_check CHECK(role IN ('STUDENT','TEACHER','ADMIN'));
CREATE TABLE IF NOT EXISTS sessions (
 token_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS portal_tickets (
 ticket_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS admin_audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action VARCHAR(80) NOT NULL,
 target_type VARCHAR(40) NOT NULL,
 target_id BIGINT NOT NULL,
 detail VARCHAR(500) NOT NULL DEFAULT '',
 created_at BIGINT NOT NULL DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT)
);
CREATE TABLE IF NOT EXISTS courses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 description TEXT NOT NULL,
 published BOOLEAN NOT NULL DEFAULT FALSE,
 created_by BIGINT REFERENCES accounts(id),
 created_at BIGINT NOT NULL DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT)
);
ALTER TABLE courses ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES accounts(id);
ALTER TABLE courses ADD COLUMN IF NOT EXISTS created_at BIGINT NOT NULL DEFAULT 0;
ALTER TABLE courses ALTER COLUMN created_at SET DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT);
UPDATE courses SET created_at=CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT) WHERE created_at=0;
CREATE TABLE IF NOT EXISTS chapters (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES courses(id),
 title VARCHAR(160) NOT NULL,
 position INT NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT)
);
ALTER TABLE chapters ADD COLUMN IF NOT EXISTS created_at BIGINT NOT NULL DEFAULT 0;
ALTER TABLE chapters ALTER COLUMN created_at SET DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT);
UPDATE chapters SET created_at=CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT) WHERE created_at=0;
CREATE TABLE IF NOT EXISTS lessons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chapter_id BIGINT NOT NULL REFERENCES chapters(id),
 title VARCHAR(160) NOT NULL,
 content TEXT NOT NULL,
 material_url VARCHAR(2000) NOT NULL DEFAULT '',
 position INT NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT)
);
ALTER TABLE lessons ADD COLUMN IF NOT EXISTS created_at BIGINT NOT NULL DEFAULT 0;
ALTER TABLE lessons ALTER COLUMN created_at SET DEFAULT CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT);
UPDATE lessons SET created_at=CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000 AS BIGINT) WHERE created_at=0;
CREATE TABLE IF NOT EXISTS lesson_progress (
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 lesson_id BIGINT NOT NULL REFERENCES lessons(id),
 completed_at BIGINT NOT NULL,
 PRIMARY KEY(user_id,lesson_id)
);
CREATE TABLE IF NOT EXISTS course_learning (
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 course_id BIGINT NOT NULL REFERENCES courses(id),
 started_at BIGINT NOT NULL,
 last_accessed_at BIGINT NOT NULL,
 PRIMARY KEY(user_id,course_id)
);
CREATE TABLE IF NOT EXISTS questions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chapter_id BIGINT NOT NULL REFERENCES chapters(id),
 prompt TEXT NOT NULL,
 option_a VARCHAR(1000) NOT NULL,
 option_b VARCHAR(1000) NOT NULL,
 option_c VARCHAR(1000) NOT NULL,
 option_d VARCHAR(1000) NOT NULL,
 correct_option INT NOT NULL CHECK(correct_option BETWEEN 0 AND 3),
 explanation TEXT NOT NULL,
 difficulty INT NOT NULL DEFAULT 1 CHECK(difficulty BETWEEN 1 AND 3),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS quiz_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 chapter_id BIGINT NOT NULL REFERENCES chapters(id),
 started_at BIGINT NOT NULL,
 deadline BIGINT NOT NULL,
 submitted_at BIGINT,
 score INT,
 total INT NOT NULL
);
CREATE TABLE IF NOT EXISTS attempt_answers (
 attempt_id BIGINT NOT NULL REFERENCES quiz_attempts(id),
 question_id BIGINT NOT NULL REFERENCES questions(id),
 position INT NOT NULL,
 prompt TEXT NOT NULL,
 option_a VARCHAR(1000) NOT NULL,
 option_b VARCHAR(1000) NOT NULL,
 option_c VARCHAR(1000) NOT NULL,
 option_d VARCHAR(1000) NOT NULL,
 correct_option INT NOT NULL,
 explanation TEXT NOT NULL,
 selected_option INT,
 PRIMARY KEY(attempt_id,question_id)
);
CREATE INDEX IF NOT EXISTS idx_attempt_user ON quiz_attempts(user_id, started_at);
CREATE INDEX IF NOT EXISTS idx_question_chapter ON questions(chapter_id);
CREATE TABLE IF NOT EXISTS study_classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES courses(id),
 teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 name VARCHAR(120) NOT NULL,
 join_code VARCHAR(12) UNIQUE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS class_enrollments (
 class_id BIGINT NOT NULL REFERENCES study_classes(id),
 student_id BIGINT NOT NULL REFERENCES accounts(id),
 enrolled_at BIGINT NOT NULL,
 PRIMARY KEY(class_id,student_id)
);
CREATE INDEX IF NOT EXISTS idx_class_teacher ON study_classes(teacher_id,active);
CREATE INDEX IF NOT EXISTS idx_enrollment_student ON class_enrollments(student_id);
CREATE TABLE IF NOT EXISTS class_announcements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL REFERENCES study_classes(id) ON DELETE CASCADE,
 author_id BIGINT NOT NULL REFERENCES accounts(id),
 body VARCHAR(2000) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_class_announcement_recent ON class_announcements(class_id,created_at DESC);
CREATE TABLE IF NOT EXISTS course_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES courses(id),
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 body VARCHAR(2000) NOT NULL,
 sent_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS course_presence (
 course_id BIGINT NOT NULL REFERENCES courses(id),
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 seen_at BIGINT NOT NULL,
 PRIMARY KEY(course_id,user_id)
);
CREATE INDEX IF NOT EXISTS idx_course_message ON course_messages(course_id,id);
CREATE TABLE IF NOT EXISTS personal_study_snapshots (
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 version BIGINT NOT NULL,
 request_id VARCHAR(64) NOT NULL,
 payload TEXT NOT NULL,
 updated_at BIGINT NOT NULL,
 PRIMARY KEY(user_id,version),
 UNIQUE(user_id,request_id)
);
